REMOVE = {
"清理.md": ["建模"],
"特徵工程.md": ["描述統計", "資料取得"],
"視覺化.md": ["互動式視覺"],
"資料取得.md": ["建模", "特徵工程"],
"描述統計.md": [],
}
ADD = {
"清理.md": ["資料倫理"],
"特徵工程.md": ["演算法"],
}

SITE = "site/資料科學"
for name, block in BLOCKS.items():
    p = os.path.join(SITE, name)
    s = open(p, encoding="utf-8").read()
    title = name[:-3]
    s = re.sub(r"^\[%s\]: .*\n" % re.escape(title), "", s, flags=re.M)
    for label in REMOVE.get(name, []):
        s = re.sub(r"^\[%s\]: .*\n" % re.escape(label), "", s, flags=re.M)
    if name in ADD:
        s = s.replace("## 連結定義", "## 連結定義\n")
        for label in ADD[name]:
            target = {"資料倫理": "資料倫理.md", "演算法": "../演算法/README.md"}[label]
            s = s.rstrip() + "\n[%s]: %s\n" % (label, target)
    s = s.replace("## 延伸閱讀", block.strip() + "\n\n## 延伸閱讀")
    open(p, "w", encoding="utf-8").write(s)
    print("updated", name)
