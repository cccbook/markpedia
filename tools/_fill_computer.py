ADD["階層式儲存"] = """
## 實務補充：層級設計的量化

儲存階層的核心是時間局部性與空間局部性：剛被存取的資料很可能再次被存取，鄰近的資料也可能接著被存取。這兩個性質讓「把熱資料往上層放」有數學與經驗的依據。

各層的數字差異極大：暫存器約 1 個時脈，SRAM 快取約 10 到 40 個時脈，DRAM 數百個時脈，SSD 數十微秒，HDD 數毫秒。這就是為什麼「先降低記憶體存取次數」通常比「換更快的處理器」更有效。

設計的代價是複雜度：每一層都需要一致的問題（寫回還是寫穿？兩層之間如何保持一致？），快取一致性協定、寫回緩衝與頁替換策略都是這場拉鋸的產物。
"""

ADD["馮諾依曼"] = """
## 實務補充：瓶頸與哈佛式對策

馮諾依曼架構的最大問題是「匯流排瓶頸」：指令與資料共用同一條通道，CPU 在任何時刻只能做取指或存取資料其中之一，導致處理器效能隨記憶體速度落後而停滯。

哈佛架構把指令與資料分置於不同記憶體與不同通道，兩者可同時傳輸，從根本上緩解瓶頸。現代處理器多採混合設計：主記憶體層面沿用馮諾依曼以維持軟體相容，快取層面則採哈佛式把指令快取與資料快取分開。

此外，馮諾依曼式的「程式與資料同體」也是自我修改程式與病毒能存在的根源；作業系統用特权分頁與 W^X 機制在硬體層面禁止同一頁同時可寫可執行，正是針對此一弱點。
"""

for name, extra in ADD.items():
    path = os.path.join(DIR, f"{name}.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if "## 實務補充" in text:
        print("skip", name)
        continue
    body, sep, defs = text.partition("## 連結定義\n")
    body = body.rstrip("\n") + "\n" + extra.strip("\n") + "\n\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(body + sep + defs)
    n = len((body + sep + defs).rstrip("\n").split("\n"))
    print(name, n)
