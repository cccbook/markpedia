SITE = "site/資料科學"
for name, block in BLOCKS.items():
    p = os.path.join(SITE, name)
    s = open(p, encoding="utf-8").read()
    title = name[:-3]
    # 移除自我定義（未被使用）
    s = re.sub(r"^\[%s\]: .*\n" % re.escape(title), "", s, flags=re.M)
    block = block.replace("[實驗設計]", "[實驗設計]")
    s = s.replace("## 延伸閱讀", block.strip() + "\n\n## 延伸閱讀")
    open(p, "w", encoding="utf-8").write(s)
    print("updated", name)
